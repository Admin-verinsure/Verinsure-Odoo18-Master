from odoo import fields, models


class CustomerStatementGenerationLog(models.Model):
    _name = 'customer.statement.generation.log'
    _description = 'Customer Statement Generation Log'
    _order = 'generated_at desc, id desc'

    partner_id = fields.Many2one('res.partner', string='Customer', required=True, index=True,
                                 ondelete='cascade')
    company_id = fields.Many2one('res.company', string='Company', required=True, index=True)
    user_id = fields.Many2one('res.users', string='Generated By')
    generated_at = fields.Datetime(string='Generated On', required=True,
                                   default=fields.Datetime.now, index=True)
    start_date = fields.Date(string='Statement From')
    end_date = fields.Date(string='Statement To')
    output = fields.Selection([('pdf', 'PDF'), ('excel', 'Excel')], string='Output')


class CustomerStatementWizard(models.TransientModel):
    _inherit = 'customer.statement.wizard'

    def _payment_reminder_track_generation(self, output):
        """Remember that a person generated a statement for this customer. The
        statements built by the reminder itself never go through these buttons."""
        for wizard in self:
            self.env['customer.statement.generation.log'].sudo().create({
                'partner_id': wizard.partner_id.id,
                'company_id': self.env.company.id,
                'user_id': self.env.user.id,
                'start_date': wizard.start_date,
                'end_date': wizard.end_date,
                'output': output,
            })

    def customer_statements_pdf_report(self):
        action = super().customer_statements_pdf_report()
        self._payment_reminder_track_generation('pdf')
        return action

    def customer_statements_excel_report(self):
        action = super().customer_statements_excel_report()
        self._payment_reminder_track_generation('excel')
        return action
